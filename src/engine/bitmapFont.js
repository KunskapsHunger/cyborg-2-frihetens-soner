const GLYPHS = new Map();
for (const [ch, def] of Object.entries(G)) {
  const rows = def.split('|').map((r) => [...r].map((c) => c === '#'));
  // 10-row glyphs start two rows above the cap line.
  GLYPHS.set(String(ch), { rows, top: rows.length - 8 });
}

/** True when the character renders as itself (not the '?' fallback). */
export function hasGlyph(ch) {
  return GLYPHS.has(ch) || GLYPHS.has(ch.toUpperCase());
}

export const GLYPH_W = 6;
export const GLYPH_H = 9;

export function textWidth(text, scale = 1) {
  return text.length * GLYPH_W * scale;
}

/** Draw text; returns width. Optional 1px drop shadow for legibility. */
export function drawText(g, text, x, y, color = '#d8d0b8', { scale = 1, shadow = '#000', align = 'left' } = {}) {
  let ox = Math.round(x);
  if (align === 'center') ox = Math.round(x - textWidth(text, scale) / 2);
  else if (align === 'right') ox = Math.round(x - textWidth(text, scale));
  const oy = Math.round(y);
  const pass = (dx, dy, col) => {
    g.fillStyle = col;
    let cx = ox + dx;
    for (const ch of text) {
      const glyph = GLYPHS.get(ch) ?? GLYPHS.get(ch.toUpperCase()) ?? GLYPHS.get('?');
      glyph.rows.forEach((row, r) => {
        const py = oy + dy + (r - glyph.top) * scale;
        for (let c = 0; c < 5; c++) {
          if (row[c]) g.fillRect(cx + c * scale, py, scale, scale);
        }
      });
      cx += GLYPH_W * scale;
    }
  };
  if (shadow) pass(scale, scale, shadow);
  pass(0, 0, color);
  return textWidth(text, scale);
}

/** Greedy word wrap to a max pixel width. */
export function wrapText(text, maxWidth, scale = 1) {
  const maxChars = Math.max(1, Math.floor(maxWidth / (GLYPH_W * scale)));
  const lines = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const next = line ? `${line} ${word}` : word;
      if (next.length > maxChars && line) {
        lines.push(line);
        line = word;
      } else {
        line = next;
      }
    }
    lines.push(line);
  }
  return lines;
}
